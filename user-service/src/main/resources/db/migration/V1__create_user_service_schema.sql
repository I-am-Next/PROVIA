CREATE TABLE user_profiles (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                               auth_user_id VARCHAR(255) NOT NULL,
                               email VARCHAR(255) NOT NULL,
                               first_name VARCHAR(255),
                               last_name VARCHAR(255),
                               phone VARCHAR(255),
                               profile_photo_url VARCHAR(255),
                               created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

                               CONSTRAINT user_profiles_pkey
                                   PRIMARY KEY (id),

                               CONSTRAINT uk_user_profiles_auth_user_id
                                   UNIQUE (auth_user_id)
);

CREATE TABLE user_device_tokens (
                                    id UUID NOT NULL,
                                    user_id UUID NOT NULL,
                                    device_token VARCHAR(255) NOT NULL,
                                    device_type VARCHAR(255) NOT NULL,
                                    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                                    last_used_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

                                    CONSTRAINT user_device_tokens_pkey
                                        PRIMARY KEY (id),

                                    CONSTRAINT uk_user_device_tokens_device_token
                                        UNIQUE (device_token)
);

CREATE INDEX idx_user_device_tokens_user_id
    ON user_device_tokens (user_id);

CREATE INDEX idx_user_device_tokens_last_used_at
    ON user_device_tokens (last_used_at);